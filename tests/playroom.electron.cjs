// Run with node_modules/.bin/electron tests/playroom.electron.cjs.
// Actual window manager/preloads/UI and pet store; all saves stay in memory.
const { app, BrowserWindow, ipcMain } = require('electron');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'qq-pet-playroom-'));
app.setPath('userData', path.join(temp, 'userData'));
app.on('window-all-closed', () => {});
const saves = [];
global.$Store = { setItem(key, value) { saves.push({ key, value: JSON.parse(JSON.stringify(value)) }); } };
require('../src/ini/pet');
const { companion } = require('../src/service/gameplay/companion');
const timeout = setTimeout(() => app.exit(2), 30000);
const delay = ms => new Promise(r => setTimeout(r, ms));
async function until(fn) {
  for (let i = 0; i < 100; i++) { if (await fn()) return; await delay(100); }
  throw new Error('Timed out waiting for UI');
}
app.whenReady().then(async () => {
  global.windowsMain = new (require('../src/windows/window'))();
  global.openSpeak = () => {};
  setPetInfo({ info: { sex: 'GG', name: '测试企鹅', host: '测试', health: 5, yb: 300, mood: 800, hunger: 1500, clean: 1500, growth: 500 }, maxInfo: { level: 10, hunger: 3000, clean: 3000 } });
  const room = require('../src/windows/popups/playroom/main');
  room.cleate();
  console.log('CHECK: opening playroom');
  await until(() => room.window && room.window.webContents.executeJavaScript("document.querySelectorAll('.task-card').length===4"));
  const win = room.window;
  console.log('CHECK: task cards rendered');
  const task = companion().view().daily.tasks[0];
  companion().record(task.id, task.target);
  await until(() => win.webContents.executeJavaScript("!document.querySelector('.task-card button').disabled"));
  await win.webContents.executeJavaScript("document.querySelector('.task-card button').click()");
  await until(() => getPetInfo().info.yb === 350);
  const rewardSave = saves.filter(s => s.key === 'pet').at(-1).value;
  assert.equal(rewardSave.playroom.daily.tasks[0].claimed, true);
  assert.equal(rewardSave.info.yb, 350);
  assert.equal(rewardSave.info.name, '测试企鹅', 'unrelated pet fields are preserved');
  assert.equal(rewardSave.info.hunger, 1500);
  await win.webContents.executeJavaScript("electronAPI.playroomAction({type:'claim',day:'" + rewardSave.playroom.daily.day + "',id:'" + task.id + "'})");
  await delay(100); assert.equal(getPetInfo().info.yb, 350);
  await win.webContents.executeJavaScript("const select=document.getElementById('face-mode'); select.value='1'; select.dispatchEvent(new Event('change'))");
  await until(() => getPetInfo().playroom.settings.faceMode === 1);
  const screenshot = path.join(temp, 'playroom.png');
  fs.writeFileSync(screenshot, (await win.webContents.capturePage()).toPNG());
  const closed = new Promise(resolve => win.once('closed', resolve));
  win.close();
  await closed;
  console.log('CHECK: claim/settings saved, reopening');
  room.cleate();
  await until(() => room.window && room.window.webContents.executeJavaScript("document.querySelector('.task-card button')?.textContent==='已领取'"));
  assert.equal(await room.window.webContents.executeJavaScript("document.getElementById('face-mode').value"), '1');
  let ready = false;
  ipcMain.on('smallGame_h_bus_m', (_, data) => { if (data.event === 'gameReady') ready = true; });
  require('../src/windows/popups/smallGame/main').cleate();
  console.log('CHECK: opening game selector');
  await until(() => windowsMain.wins.smallGame?.win?.webContents.executeJavaScript("document.querySelectorAll('.menu_item').length>0"));
  const game = windowsMain.wins.smallGame.win;
  await game.webContents.executeJavaScript("Array.from(document.querySelectorAll('.menu_item')).find(el=>el.textContent.trim()==='泡泡').click()");
  await until(() => ready);
  const status = await game.webContents.executeJavaScript("({frames:document.getElementById('gameMain').ruffle().metadata.numFrames,input:getComputedStyle(document.getElementById('gameMain')).pointerEvents,focus:document.activeElement.id})");
  assert.ok(status.frames > 0); assert.equal(status.input, 'auto'); assert.equal(status.focus, 'gameMain');
  game.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Space' });
  game.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Space' });
  game.close();
  const { travel } = require('../src/service/gameplay/travel');
  const { startGameplay } = require('../src/service/gameplay/runtime');
  let travelTime = Date.now();
  travel().now = () => travelTime;
  travel().random = () => 0;
  const stopGameplay = startGameplay();
  room.cleate('travel');
  const tripUI = require('../src/windows/popups/travel/main');
  await until(() => tripUI.window && tripUI.window.webContents.executeJavaScript("document.querySelector('.travel-map')!==null"));
  const tripWin = tripUI.window;
  const roomWin = room.window;
  assert.equal(await tripWin.webContents.executeJavaScript("document.querySelectorAll('.travel-map path').length"), 35);
  assert.equal(await tripWin.webContents.executeJavaScript("document.querySelector('.travel-map').getAttribute('viewBox')"), '0 0 560 557');
  await tripWin.webContents.executeJavaScript("document.querySelector('.start-travel').click()");
  await until(() => !!getPetInfo().activeOption.trip);
  assert.equal(getPetInfo().activeOption.trip.city, '北京市');
  travelTime += 55 * 60000;
  travel().tick();
  await until(() => tripWin.webContents.executeJavaScript("document.querySelectorAll('.travel-map .visited').length===1"));
  assert.equal(getPetInfo().playroom.travel.postcards.length, 1);
  await tripWin.webContents.executeJavaScript('new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))');
  fs.writeFileSync(path.join(temp, 'travel-map.png'), (await tripWin.webContents.capturePage()).toPNG());
  await roomWin.webContents.executeJavaScript("document.querySelectorAll('.playroom-tabs button')[2].click(); document.querySelector('.travel-postcards button').click()");
  await until(() => getPetInfo().playroom.travel.postcards[0].read);
  await roomWin.webContents.executeJavaScript("document.querySelector('.travel-letter button').click()");
  await until(() => getPetInfo().info.yb === 390);
  assert.equal(getPetInfo().playroom.travel.souvenirs.length, 1);
  await roomWin.webContents.executeJavaScript("electronAPI.playroomAction({type:'claimEncounter',id:1})");
  await delay(100); assert.equal(getPetInfo().info.yb, 390);
  await roomWin.webContents.executeJavaScript('new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))');
  fs.writeFileSync(path.join(temp, 'postcard.png'), (await roomWin.webContents.capturePage()).toPNG());
  assert.equal(getPetInfo().playroom.travel.photos.length, 1);
  assert.equal(travel().view().availablePhotos, 231);
  await roomWin.webContents.executeJavaScript("document.querySelectorAll('.playroom-tabs button')[3].click(); document.querySelector('.album-grid button').click()");
  await until(() => roomWin.webContents.executeJavaScript("document.querySelector('.album-preview img')?.complete && document.querySelector('.album-preview img').naturalWidth>0"));
  await roomWin.webContents.executeJavaScript('new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))');
  fs.writeFileSync(path.join(temp, 'album.png'), (await roomWin.webContents.capturePage()).toPNG());
  stopGameplay();
  console.log('PASS: real task UI/save, settings/reopen, Ruffle game/input, 35-region travel map, return/mail/souvenir reward once, actual photo album. Screenshots: ' + temp);
  clearTimeout(timeout);
  for (const w of BrowserWindow.getAllWindows()) w.destroy();
  app.quit();
}).catch(error => { console.error(error); for (const w of BrowserWindow.getAllWindows()) w.destroy(); app.exit(1); });
